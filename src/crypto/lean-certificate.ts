export interface LeanCertificateSource {
  n: string;
  language: 'lean4';
  verificationStatus: 'generated_not_checked';
  dependency: 'Mathlib';
  source: string;
  instructions: string;
  caveat: string;
}

export function generateLeanPrimeCertificateSource(value: string): LeanCertificateSource {
  if (!/^(?:0|[1-9][0-9]{0,299})$/.test(value)) {
    throw new Error('n must be a non-negative decimal integer with at most 300 digits.');
  }
  const n = BigInt(value);
  if (n < 2n) throw new Error('A primality certificate can only be generated for n >= 2.');
  const source = [
    'import Mathlib',
    '',
    '-- Generated by Reconcile MCP.',
    '-- Compile with: lake env lean PrimeCertificate.lean',
    '-- A successful Lean kernel check proves this concrete proposition.',
    'theorem recon_prime_certificate : Nat.Prime ' + n.toString() + ' := by',
    '  norm_num',
    '',
  ].join('\n');
  return {
    n: n.toString(),
    language: 'lean4',
    verificationStatus: 'generated_not_checked',
    dependency: 'Mathlib',
    source,
    instructions: 'Save source as PrimeCertificate.lean in a Lean 4 project with Mathlib, then run lake env lean PrimeCertificate.lean. A successful exit means Lean checked the theorem proof with its kernel.',
    caveat: 'This endpoint generates a proof script; it does not run Lean, does not claim the proof has compiled, and does not produce a portable compact Pocklington/ECPP certificate. Large inputs may make norm_num slow or fail to synthesize a proof efficiently.',
  };
}